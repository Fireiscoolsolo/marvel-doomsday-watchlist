import { createServer } from 'node:http';
import { createHash, randomBytes, scrypt, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';
import { mkdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const derive = promisify(scrypt);
const sessionSeconds = 30 * 24 * 60 * 60;
const hashToken = token => createHash('sha256').update(token).digest('hex');
const passwordHash = (password, salt) =>
  derive(password, salt, 64, { N: 131072, r: 8, p: 1, maxmem: 192 * 1024 * 1024 });

function sqlite(database) {
  const db = new DatabaseSync(database);
  db.exec('PRAGMA foreign_keys = ON; PRAGMA journal_mode = WAL; PRAGMA busy_timeout = 5000;');
  return { query: (sql, ...args) => db.prepare(sql).all(...args), close: () => db.close() };
}

export async function initializeStorage(storage, postgres = false) {
  await storage.query('CREATE TABLE IF NOT EXISTS accounts (id ' +
    (postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY' : 'INTEGER') +
    ' PRIMARY KEY, username TEXT UNIQUE NOT NULL, salt TEXT NOT NULL, digest TEXT NOT NULL)');
  await storage.query('CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, account INTEGER NOT NULL REFERENCES accounts(id), expires BIGINT NOT NULL)');
  await storage.query('CREATE TABLE IF NOT EXISTS watched (account INTEGER NOT NULL REFERENCES accounts(id), title TEXT NOT NULL, PRIMARY KEY (account, title))');
}

export async function watchlistServer({ database, storage = sqlite(database), origin, html, postgres = false }) {
  await initializeStorage(storage, postgres);
  const query = storage.query;
  const secure = new URL(origin).protocol === 'https:';
  const cookieName = secure ? '__Host-watchlist' : 'watchlist';
  const cookie = (token, age) => cookieName + '=' + token + '; Path=/; HttpOnly; SameSite=Lax; Max-Age=' + age + (secure ? '; Secure' : '');
  const titles = new Set([...html.matchAll(/<tr [^>]*\bdata-id="(\d+)"/g)].map(match => match[1]));
  const attempts = new Map();
  let hashing = false;

  function respond(res, status, body, headers = {}) {
    res.writeHead(status, {
      'Content-Type': 'application/json; charset=utf-8',
      'Cache-Control': 'no-store',
      'X-Content-Type-Options': 'nosniff',
      ...headers,
    });
    res.end(JSON.stringify(body));
  }
  async function body(req) {
    let size = 0;
    const chunks = [];
    for await (const chunk of req) {
      size += chunk.length;
      if (size > 4096) return null;
      chunks.push(chunk);
    }
    try { return JSON.parse(Buffer.concat(chunks)); } catch { return null; }
  }
  function blocked(address, username) {
    const now = Date.now();
    for (const [key, record] of attempts) {
      if (now >= record.until) attempts.delete(key);
    }
    const keys = ['ip:' + address, 'name:' + username];
    if (attempts.size >= 10000 || keys.some(key => (attempts.get(key)?.count ?? 0) >= 10)) return true;
    for (const key of keys) {
      const record = attempts.get(key) ?? { count: 0, until: now + 10 * 60 * 1000 };
      record.count++;
      attempts.set(key, record);
    }
    return false;
  }
  const server = createServer(async (req, res) => {
    try {
      const path = new URL(req.url, origin).pathname;
      if (req.method === 'GET' && (path === '/' || path === '/index.html')) {
        res.writeHead(200, {
          'Content-Type': 'text/html; charset=utf-8',
          'X-Content-Type-Options': 'nosniff',
          'Referrer-Policy': 'same-origin',
          'Content-Security-Policy': "default-src 'none'; script-src 'self' 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'self'; form-action 'self'; base-uri 'none'; frame-ancestors 'none'",
        });
        return res.end(html);
      }
      if (!path.startsWith('/api/')) return respond(res, 404, { error: 'Page not found.' });
      const now = Math.floor(Date.now() / 1000);
      const token = (req.headers.cookie ?? '').match(new RegExp('(?:^|;\\s*)' + cookieName + '=([a-f0-9]{64})(?:;|$)'))?.[1];
      const account = token ? (await query('SELECT accounts.id, accounts.username FROM sessions JOIN accounts ON accounts.id = sessions.account WHERE token = ? AND expires > ?', hashToken(token), now))[0] : undefined;
      const status = async profile => ({
        username: profile?.username ?? null,
        watched: profile ? (await query('SELECT title FROM watched WHERE account = ?', profile.id)).map(row => row.title) : [],
      });
      if (req.method === 'GET' && path === '/api/session') return respond(res, 200, await status(account));
      if (req.method !== 'POST') return respond(res, 405, { error: 'Method unavailable.' });
      if (req.headers.origin !== origin) return respond(res, 403, { error: 'Request must come from the watchlist.' });
      if (!/^application\/json(?:;|$)/i.test(req.headers['content-type'] ?? '')) {
        return respond(res, 415, { error: 'JSON is required.' });
      }
      const data = await body(req);
      if (!data || typeof data !== 'object') return respond(res, 400, { error: 'Invalid request.' });
      if (path === '/api/login' || path === '/api/register') {
        const username = typeof data.username === 'string' ? data.username.trim().toLowerCase() : '';
        const password = typeof data.password === 'string' ? data.password : '';
        if (!/^[a-z0-9_]{3,32}$/.test(username) || password.length < 15 || password.length > 128) {
          return respond(res, 400, { error: 'Use 3–32 letters, numbers or underscores and a password of 15–128 characters.' });
        }
        if (hashing || blocked(req.socket.remoteAddress, username)) {
          return respond(res, 429, { error: 'Too many sign-in attempts. Try again later.' });
        }
        const registering = path === '/api/register';
        let record;
        let salt;
        let digest;
        hashing = true;
        try {
          if (!registering) [record] = await query('SELECT id, username, salt, digest FROM accounts WHERE username = ?', username);
          salt = registering ? randomBytes(16).toString('hex') : record?.salt ?? '0'.repeat(32);
          digest = await passwordHash(password, salt);
        } finally { hashing = false; }
        let profile = record;
        if (registering) {
          [profile] = await query('INSERT INTO accounts (username, salt, digest) VALUES (?, ?, ?) ON CONFLICT (username) DO NOTHING RETURNING id, username', username, salt, digest.toString('hex'));
          if (!profile) return respond(res, 409, { error: 'That username is unavailable.' });
        } else if (!record || !timingSafeEqual(digest, Buffer.from(record.digest, 'hex'))) {
          return respond(res, 401, { error: 'Username or password is incorrect.' });
        }
        const nextToken = randomBytes(32).toString('hex');
        const progress = await status(profile);
        await query('INSERT INTO sessions (token, account, expires) VALUES (?, ?, ?)', hashToken(nextToken), profile.id, now + sessionSeconds);
        await query('DELETE FROM sessions WHERE expires <= ? OR token = ?', now, token ? hashToken(token) : '');
        return respond(res, 200, progress, { 'Set-Cookie': cookie(nextToken, sessionSeconds) });
      }
      if (path === '/api/logout') {
        if (token) await query('DELETE FROM sessions WHERE token = ?', hashToken(token));
        return respond(res, 200, await status(), { 'Set-Cookie': cookie('', 0) });
      }
      if (path === '/api/progress') {
        if (!account) return respond(res, 401, { error: 'Sign in to save to your account.' });
        if (!titles.has(data.title) || typeof data.watched !== 'boolean') {
          return respond(res, 400, { error: 'Invalid checklist entry.' });
        }
        if (data.watched) {
          await query('INSERT INTO watched (account, title) VALUES (?, ?) ON CONFLICT (account, title) DO NOTHING', account.id, data.title);
        } else {
          await query('DELETE FROM watched WHERE account = ? AND title = ?', account.id, data.title);
        }
        return respond(res, 200, { saved: true });
      }
      return respond(res, 404, { error: 'Page not found.' });
    } catch {
      respond(res, 500, { error: 'The account service could not save your request. Try again.' });
    }
  });
  server.on('close', () => storage.close());
  return server;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const port = Number(process.env.PORT || 3000);
  const address = new URL(process.env.PUBLIC_ORIGIN || process.env.RENDER_EXTERNAL_URL || 'http://localhost:' + port);
  if (address.protocol !== 'https:' && address.origin !== 'http://localhost:' + port) {
    throw new Error('Use HTTPS for any public deployment.');
  }
  const html = readFileSync(new URL('./index.html', import.meta.url), 'utf8');
  let options;
  if (process.env.DATABASE_URL) {
    const { Pool } = await import('pg');
    const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 3, connectionTimeoutMillis: 10000 });
    pool.on('error', () => console.error('An idle database connection failed.'));
    const query = async (sql, ...args) => {
      let index = 0;
      const result = await pool.query(sql.replace(/\?/g, () => '$' + ++index), args);
      return result.rows;
    };
    options = { postgres: true, storage: { query, close: () => pool.end() } };
  } else {
    if (process.env.RENDER_EXTERNAL_URL && !process.env.WATCHLIST_DATA_DIR) {
      throw new Error('Set DATABASE_URL for durable storage on Render Free.');
    }
    const directory = resolve(process.env.WATCHLIST_DATA_DIR || '.watchlist-data');
    mkdirSync(directory, { recursive: true });
    options = { database: resolve(directory, 'watchlist.sqlite') };
  }
  const server = await watchlistServer({ ...options, origin: address.origin, html });
  server.listen(port, process.env.HOST || (process.env.RENDER_EXTERNAL_URL ? '0.0.0.0' : '127.0.0.1'), () => console.log('Watchlist: ' + address.origin));
}
